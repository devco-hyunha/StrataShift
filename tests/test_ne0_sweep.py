"""p5-08 AC3 gate: engine LOAD gate + rope gate sweep on the emitted GGUF.

Engine `tensor_payload_bytes` (gguf_reader.hpp:505, pin c566ff4) computes the payload
only when the ENGINE shape's first dim is a multiple of the type's block elems; the
p5-07 AC5 measured refusal was 30 `ffn_down [2112,2816]` Q4_K (2112 % 256 = 64) —
the dense gate fix (`_dense_select`, p5-08 AC1) must drive FAIL to 0. The rope gate
(engine gemma4.cpp:207, pin c566ff4 — TK1 RUN FAIL rc=1 "the GGUF has no tensor
rope_freqs.weight") requires the derived global tensor F32 [n_rot/2, 1] with the
engine float64 values `theta ** (-2i/n_rot)` cast to float32 (rope_parity.cpp
header) whenever the pattern carries a FULL layer.

- mini: the p5-08 mini fixture (pattern [1,1,0], one full layer) must pass the sweep.
- real: the p5-06 scratch GGUF (regenerated by scripts/p5_gemma4_smoke.py after the
  fix) must pass FAIL=0 + rope PASS; skipped when the emit has not been re-run.
"""
from __future__ import annotations

import json
import os
import pathlib
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))
from test_gemma4_mini_emit import GUARD, build_mini  # noqa: E402
from stratashift.polystrata.engine_paths import (  # noqa: E402
    ENV_SCRATCH, describe_missing, resolve_engine_paths)

REAL_GGUF = resolve_engine_paths().scratch / "p5-06-out" / "gemma4-emitted.gguf"


def _run_sweep(gguf: pathlib.Path) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(ROOT / "scripts" / "p5_ne0_sweep.py"),
                           str(gguf)], capture_output=True, text=True)


def test_mini_sweep_engine_load_and_rope_gate(tmp_path):
    model = tmp_path / "mini"
    build_mini(model)
    guard = tmp_path / "guard.json"
    guard.write_text(json.dumps(GUARD))
    gguf = tmp_path / "mini.gguf"
    env = dict(os.environ, PYTHONPATH=str(ROOT / "src"))
    r = subprocess.run([sys.executable, str(ROOT / "src" / "stratashift" / "cli" / "main.py"),
                        "convert", str(model), "--out", str(tmp_path / "pack"),
                        "--emit-gguf", str(gguf), "--hf-emit",
                        "--guard-keys", str(guard), "--dense-type", "Q4_K"],
                       capture_output=True, text=True, env=env)
    assert r.returncode == 0, r.stdout + r.stderr
    s = _run_sweep(gguf)
    assert s.returncode == 0, s.stdout + s.stderr
    assert "rope gate PASS" in s.stdout
    assert "FAIL=0" in s.stdout


def test_real_gemma4_sweep_engine_load_and_rope_gate():
    if not REAL_GGUF.is_file():
        pytest.skip("p5-06 scratch GGUF absent — re-run scripts/p5_gemma4_smoke.py "
                    "with the p5-08 fix (emit regenerates it): "
                    + describe_missing(REAL_GGUF, ENV_SCRATCH))
    s = _run_sweep(REAL_GGUF)
    assert s.returncode == 0, s.stdout + s.stderr
    assert "rope gate PASS" in s.stdout
    assert "FAIL=0" in s.stdout
